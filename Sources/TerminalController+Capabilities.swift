extension TerminalController {
    nonisolated func v2CapabilitiesWithBrowserDesignMode(params: [String: Any]) -> [String: Any] {
        var capabilities = v2Capabilities()
        if params[WorkspaceRemoteRelayCommandRewriter.remoteWorkspaceIDKey] != nil {
            // A capability name is discovery, never a grant. Do not return the
            // local socket or access mode.
            return [
                "protocol": "bree-socket", "version": 2, "scope": "remote_workspace",
                "methods": RemoteRelayCommandPolicy().permittedMethods(
                    from: capabilities["methods"] as? [String] ?? []
                )
            ]
        }
        var methods = capabilities["methods"] as? [String] ?? []
        for method in ["browser.design_mode.set", "browser.design_mode.status"]
            where !methods.contains(method)
        {
            methods.append(method)
        }
        capabilities["methods"] = methods.sorted()
        return capabilities
    }

